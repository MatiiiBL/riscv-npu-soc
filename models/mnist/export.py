"""Export the INT8 MLP and a slice of the test set as C headers for firmware.

Writes sw/bench/mnist/model.h (weights in the NPU's N x K layout, biases and
requantization parameters) and sw/bench/mnist/testset.h (the first --count
test images, their labels and the predictions of int8_ref.py, which the
firmware must reproduce exactly). The headers are committed so firmware
builds need no Python.

Usage: python export.py [--count 100]
"""

import argparse
import pathlib

import numpy as np

import int8_ref
import mnist_data

OUT_DIR = pathlib.Path(__file__).resolve().parents[2] / "sw" / "bench" / "mnist"
PER_LINE = 16


def c_values(flat, indent):
    return "\n".join(
        indent + ", ".join(str(int(v)) for v in flat[i : i + PER_LINE]) + ","
        for i in range(0, len(flat), PER_LINE)
    )


def c_array(ctype, name, values, dims):
    """A const, word-aligned 1-D or 2-D C array; word alignment lets the NPU DMA it."""
    values = np.asarray(values).reshape(dims)
    if len(dims) == 1:
        body = c_values(values, "    ")
    else:
        body = "\n".join("    {\n" + c_values(row, "        ") + "\n    }," for row in values)
    shape = "".join(f"[{d}]" for d in dims)
    return f"static const {ctype} {name}{shape} __attribute__((aligned(4))) = {{\n{body}\n}};\n"


def header(guard, doc, body):
    return (
        f"/*\n * {doc}\n *\n * Generated by models/mnist/export.py. Do not edit.\n */\n"
        f"#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n\n{body}\n#endif /* {guard} */\n"
    )


def model_header(m):
    hidden, n_in = m["w1"].shape
    n_out = m["w2"].shape[0]
    body = (
        f"#define MNIST_IN      {n_in}\n"
        f"#define MNIST_HIDDEN  {hidden}\n"
        f"#define MNIST_OUT     {n_out}\n\n"
        "/* Hidden layer requantization: h = clamp(relu((acc * QMULT1 + 2^(SHIFT1-1)) >> SHIFT1)).\n"
        f" * QMULT1 / 2^SHIFT1 = {int(m['qmult1']) / 2 ** int(m['shift1']):.9g}"
        f" ~ s_x * s_w1 / s_h = {float(m['s_x'] * m['s_w1'] / m['s_h']):.9g} */\n"
        f"#define MNIST_QMULT1  {int(m['qmult1'])}\n"
        f"#define MNIST_SHIFT1  {int(m['shift1'])}\n\n"
        "/* Layer 1: hidden = relu(requant(x * w1^T + b1)), INT8 out. */\n"
        + c_array("int8_t", "mnist_w1", m["w1"], (hidden, n_in))
        + c_array("int32_t", "mnist_b1", m["b1"], (hidden,))
        + "\n/* Layer 2: logits = hidden * w2^T + b2, INT32 out. */\n"
        + c_array("int8_t", "mnist_w2", m["w2"], (n_out, hidden))
        + c_array("int32_t", "mnist_b2", m["b2"], (n_out,))
    )
    return header("MNIST_MODEL_H", f"INT8 MNIST MLP {n_in}-{hidden}-{n_out} (weights are out x in).", body)


def testset_header(images, labels, expected):
    n, n_in = images.shape
    body = (
        f"#define MNIST_TEST_COUNT {n}\n\n"
        "/* INT8 images (pixel * 127 / 255, rounded), one row of 784 per image. */\n"
        + c_array("int8_t", "mnist_test_images", images, (n, n_in))
        + "\n/* Ground-truth digits. */\n"
        + c_array("uint8_t", "mnist_test_labels", labels, (n,))
        + "\n/* Predictions of models/mnist/int8_ref.py: the firmware must match these. */\n"
        + c_array("uint8_t", "mnist_test_expected", expected, (n,))
    )
    return header("MNIST_TESTSET_H", f"First {n} MNIST test images.", body)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--count", type=int, default=100)
    args = ap.parse_args()

    model = int8_ref.load_model()
    _, _, test_px, test_y = mnist_data.load()
    images = int8_ref.quantize_input(test_px[: args.count])
    labels = test_y[: args.count]
    expected = int8_ref.predict(model, images)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "model.h").write_text(model_header(model))
    (OUT_DIR / "testset.h").write_text(testset_header(images, labels, expected))
    correct = int((expected == labels).sum())
    print(f"wrote {OUT_DIR / 'model.h'} and {OUT_DIR / 'testset.h'}")
    print(f"INT8 model on these {args.count} images: {correct}/{args.count} correct")


if __name__ == "__main__":
    main()
